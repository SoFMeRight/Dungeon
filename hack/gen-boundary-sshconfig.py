#!/usr/bin/env python3
"""Generates bash/boundary/optcp.sshconfig and optcp.windows.sshconfig from the targets
declared in the Boundary configuration overlay, so `ssh <target>` opens a Boundary session
with the person's own certificate. Run after changing TARGETS; the result is committed."""
import pathlib, re, yaml

root = pathlib.Path(__file__).resolve().parent.parent
patch = root / 'fluxcd/infrastructure/services/overlays/production/phase-04-platform/boundary/configuration-patch.yaml'
env = {e['name']: e.get('value') for e in yaml.safe_load(patch.read_text())['spec']['template']['spec']['containers'][0]['env']}
names = [l.split()[0] for l in env['TARGETS'].splitlines() if l.strip()]
project = env['PROJECT_NAME']
addr = env['OIDC_API_URL_PREFIX']

def render(exec_cmd, relay, label):
    out = [f"# Generated by hack/gen-boundary-sshconfig.py from the Boundary targets ({label}). Include",
           "# it from ~/.ssh/config and keep the optcp-cert script beside it; `ssh <target>` then",
           "# refreshes the certificate and opens the session through Boundary.",
           f"Match host {','.join(names)} exec \"{exec_cmd}\"",
           "    IdentitiesOnly yes", ""]
    for n in names:
        out += [f"Host {n}",
                f"    ProxyCommand boundary connect -addr {addr} -target-name {n} -target-scope-name {project} -exec {relay} -- {{{{boundary.ip}}}} {{{{boundary.port}}}}",
                ""]
    return "\n".join(out)

(root / 'bash/boundary/optcp.sshconfig').write_text(render('sh %d/.ssh/optcp-cert.sh', 'nc', 'POSIX'))
(root / 'bash/boundary/optcp.windows.sshconfig').write_text(render('powershell -NoProfile -ExecutionPolicy Bypass -File %d\\.ssh\\optcp-cert.ps1', 'ncat', 'Windows'))
print(f"{len(names)} targets")
